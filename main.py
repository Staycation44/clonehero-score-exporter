# CH uses little endian
def to_int(bytes):
    return int.from_bytes(bytes, "little")

# FIX: newer songcache.bin stores certain 4-byte ints "rotated"
# This only affects handle_metadata
def to_int_rot(bytes):
    return bytes[1] | (bytes[2] << 8) | (bytes[3] << 16) | (bytes[0] << 24)

def safe_open(filename):
    # CHANGE: look in DEFAULT_CH_DIR rather than the current directory
    path = os.path.join(DEFAULT_CH_DIR, filename)
    try:
        bin = open(path, "rb")
    except FileNotFoundError:
        # These files are generated by the game, fail if not there
        sys.exit(f"Error: {filename} not found at {path}.\n"
                  f"Edit DEFAULT_CH_DIR at the top of this script if your "
                  f"Clone Hero data lives somewhere else.")
    else:
        return bin

def get_difficulty(index):
    lookup = ["easy", "medium", "hard", "expert"]
    return lookup[index]

def get_instrument(index):
    # TODO: full list 
    lookup = ["lead", "bass", "rhythm", "3", "4", "5", "6", "keys"]
    return lookup[index] if index < len(lookup) else str(index) 

def handle_instrument(bin, info_dict, checksum):
    # The next 2 bytes should identify the instrument 
    instrument = get_instrument( to_int( bin.read(2) ) )
    # The next byte is the difficulty 
    difficulty = get_difficulty( to_int( bin.read(1) ) )
    # The next 2 bytes is the percentage numerator
    numerator = to_int( bin.read(2) )
    # The next 2 bytes is the percentage denominator
    denominator = to_int( bin.read(2) )
    # The next byte is the number of stars 
    num_stars = to_int( bin.read(1) )
    # The next 4 bytes make the number 1 
    bin.read(4)
    # The next 4 bytes is the score 
    score = to_int( bin.read(4) )
    percentage = round(numerator / denominator * 100, 1) if denominator else 0
    # Write this data to the output 
    info_dict[checksum]["instruments"][instrument] = {
        "difficulty": difficulty,
        "percentage": percentage, 
        "stars": num_stars,
        "score": score
    }

def handle_song(bin, info_dict, checksum_order):
    # First 16 bytes are MD5 hash of notes.mid of song
    checksum = str(bin.read(16).hex())
    # CHANGE: track checksum order so scoresext.bin and songcache.bin can be matched up to checksums
    checksum_order.append(checksum)
    # cache/score order changed, so make sure the checksum is in the info_dict before adding scores
    info_dict.setdefault(checksum, {})
    # Next byte is the number of instruments that have scores 
    num_scores = to_int( bin.read(1) )
    # The next bytes are the number of plays (unknown how long, 2-4)
    info_dict[checksum]["plays"] = to_int( bin.read(3) )
    # Initialize instruments dictionary 
    info_dict[checksum]["instruments"] = {}
    for instrument in range(num_scores):
        handle_instrument(bin, info_dict, checksum)


# Score data will be added to info_dict 
# order of checksums returned so scoresext.bin + songcache.bin can be matched to the correct songs
def handle_scores(info_dict):
    bin = safe_open("scoredata.bin")
    # First 4 bytes are some sort of header (i think) 
    header = bin.read(4)
    # The next 4 bytes is the number of songs that have scores 
    num_songs_played = to_int( bin.read(4) ) 
    checksum_order = []
    # Now, look through all the songs, making rows for each instrument
    for song in range(num_songs_played): 
        handle_song(bin, info_dict, checksum_order)
    # Close files
    bin.close()
    return checksum_order

# ADD: scoresext.bin is a possibly new, separate file that contains play time data (time in ms):
# anchors on the same checksums from scoredata.bin and has:
# - 1 byte giving the number of instrument scores for that song 
# - followed by that many 11-byte blocks (one per instrument in the same order as scoredata.bin)
# - Each block is 3 unused bytes, then a 4-byte little-endian "time played" (ms) for that instrument/difficulty, then 4 unused bytes
def handle_scoresext(info_dict, checksum_order):
    bin = safe_open("scoresext.bin")
    data = bin.read()
    bin.close()
    pos = 8  # header(4) + song count(4)
    for i, checksum in enumerate(checksum_order):
        expected = bytes.fromhex(checksum)
        got = data[pos:pos + 16]
        if got != expected:
            sys.exit(f"Error: scoresext.bin checksum mismatch at song {i} (pos {pos}).")
        pos += 16
        if i + 1 < len(checksum_order):
            nxt = bytes.fromhex(checksum_order[i + 1])
            idx = data.find(nxt, pos, pos + 200)
            if idx == -1:
                sys.exit(f"Error: scoresext.bin couldn't resync after song {i}.")
            extra = data[pos:idx]
            pos = idx
        else:
            extra = data[pos:]
        info_dict[checksum]["ext_raw_hex"] = extra.hex()
        count = extra[0] if extra else 0
        times_played_ms = []
        for j in range(count):
            block = extra[1 + j * 11 : 1 + (j + 1) * 11]
            times_played_ms.append(to_int(block[3:7]))
        info_dict[checksum]["ext_times_played_ms"] = times_played_ms


# If the first byte is >=128, then the next byte also contains length data (possibly recursive). 
def get_real_length(bin):
    length = to_int( bin.read(1) )
    if length >= 128:
        length += (to_int( bin.read(1) ) - 1) * 128
    return length


# Gets the next n bytes given the first one or two bytes. 
def get_string(bin):
    length = get_real_length(bin)
    string = bin.read(length).decode()
    return string 


def handle_lists(bin, num):
    lookup = [None] * num
    for i in range(num):
        lookup[i] = get_string(bin)
    return lookup


def get_metalist():
    return ["Title", "Artist", "Album", "Genre", "Year", "Charter", "Playlist"]


# CHANGE: Newer cache has variable length strings between blocks
# the closest match to scoredata.bin checksums helps locate the song metadata 
# Operates on the raw file bytes to search for checksums
def find_metadata_near(data, lookups, lens, checksum_offset, window=600):
    order = get_metalist()
    start = max(0, checksum_offset - window)
    seg = data[start:checksum_offset]
    candidates = []
    for s in range(len(seg) - 28 + 1):
        idxs = []
        ok = True
        for k in range(7):
            v = to_int_rot(seg[s + k * 4: s + k * 4 + 4])
            if v >= lens[k]:
                ok = False
                break
            idxs.append(v)
        if ok:
            candidates.append((start + s + 28, idxs))
    if not candidates:
        return None
    _, idxs = max(candidates, key=lambda c: c[0])  # closest candidate to the checksum
    return {order[k]: lookups[order[k]][idxs[k]] for k in range(7)}


# Return the metadata of each played song, by checksum.
def handle_metadata(data, lookups, checksum_order):
    order = get_metalist()
    lens = [len(lookups[category]) for category in order]
    info_dict = {}
    for checksum in checksum_order:
        offset = data.find(bytes.fromhex(checksum))
        if offset == -1:
            continue  # chart no longer in the library (removed/moved)
        metadata = find_metadata_near(data, lookups, lens, offset)
        if metadata:
            info_dict[checksum] = metadata
    return info_dict


# Returns the metadata info for each played song by checksum
def handle_cache(checksum_order):
    raw = safe_open("songcache.bin")
    data = raw.read()
    raw.close()
    # Wrap the bytes in a stream so get_string/handle_lists still work
    bin = io.BytesIO(data)
    # Has a header of length 20 (?)
    bin.seek(20)
    # Stored in this order
    order = get_metalist()
    # Extract each of the cached data 
    lookups = {}
    for category in order: 
        bin.read(1) # Skip the marker 
        lookups[category] = handle_lists(bin, to_int( bin.read(4) ))
    # Checksum stored slightly differently 
    info_dict = handle_metadata(data, lookups, checksum_order)
    return info_dict



def handle_json(info_dict):
    json_string = json.dumps(info_dict, indent="\t")
    json_file = open("scores.json", "w", encoding="utf-8")
    json_file.write(json_string)
    json_file.close()


